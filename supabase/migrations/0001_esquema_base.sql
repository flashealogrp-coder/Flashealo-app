create or replace function public.actualizar_embedding_promedio()
returns trigger language plpgsql set search_path to 'public','extensions' as $function$
DECLARE
    id_identidad_afectada UUID;
    total_fotos INT;
    array_suma REAL[];
    registro_foto RECORD;
    array_huella REAL[];
    i INT;
    id_viejo UUID := NULL;
    id_nuevo UUID := NULL;
BEGIN
    IF TG_OP = 'DELETE' OR TG_OP = 'UPDATE' THEN id_viejo := OLD.identity_id; END IF;
    IF TG_OP = 'INSERT' OR TG_OP = 'UPDATE' THEN id_nuevo := NEW.identity_id; END IF;
    FOR id_identidad_afectada IN
        SELECT DISTINCT id_val FROM unnest(ARRAY[id_viejo, id_nuevo]) AS id_val WHERE id_val IS NOT NULL
    LOOP
        SELECT COUNT(*) INTO total_fotos FROM face_detections
        WHERE identity_id = id_identidad_afectada AND embedding IS NOT NULL;
        IF total_fotos = 0 THEN
            UPDATE identities SET embedding_promedio = NULL WHERE id = id_identidad_afectada;
        ELSE
            array_suma := array_fill(0.0::REAL, ARRAY[512]);
            FOR registro_foto IN
                SELECT embedding FROM face_detections
                WHERE identity_id = id_identidad_afectada AND embedding IS NOT NULL
            LOOP
                array_huella := registro_foto.embedding::REAL[];
                FOR i IN 1..512 LOOP array_suma[i] := array_suma[i] + array_huella[i]; END LOOP;
            END LOOP;
            FOR i IN 1..512 LOOP array_suma[i] := array_suma[i] / total_fotos; END LOOP;
            UPDATE identities SET embedding_promedio = array_suma::vector WHERE id = id_identidad_afectada;
        END IF;
    END LOOP;
    RETURN NULL;
END;
$function$;

create trigger trigger_auto_aprendizaje
after insert or update or delete on public.face_detections
for each row execute function public.actualizar_embedding_promedio();

create or replace function public.buscar_mis_fotos(vector_busqueda extensions.vector, id_evento uuid, umbral double precision default 0.55)
returns table(foto_url text, similitud double precision)
language plpgsql security definer set search_path to 'public','extensions' as $function$
BEGIN
  RETURN QUERY
  SELECT fd.photo_url, 1 - (fd.embedding <=> vector_busqueda) AS similitud
  FROM face_detections fd
  WHERE fd.evento_id = id_evento::text
    AND 1 - (fd.embedding <=> vector_busqueda) > umbral
  ORDER BY similitud DESC;
END;
$function$;

create or replace function public.buscar_mis_fotos_global(vector_busqueda extensions.vector, umbral double precision)
returns table(photo_url text, similitud double precision, evento_id uuid, nombre_evento text, fecha_evento date)
language plpgsql security definer set search_path to 'public','extensions' as $function$
BEGIN
  RETURN QUERY
  SELECT fd.photo_url, (1 - (fd.embedding <=> vector_busqueda))::double precision AS similitud,
         fd.evento_id::uuid, e.nombre AS nombre_evento, e.fecha_evento
  FROM face_detections fd
  JOIN eventos e ON fd.evento_id::uuid = e.id
  WHERE 1 - (fd.embedding <=> vector_busqueda) > umbral
  ORDER BY e.fecha_evento DESC, similitud DESC;
END;
$function$;

create or replace function public.match_faces(query_embedding extensions.vector, match_threshold double precision, match_count integer, p_evento_id text)
returns table(id uuid, photo_url text, similarity double precision)
language sql stable security definer set search_path to 'public','extensions' as $function$
  select face_detections.id, face_detections.photo_url,
         1 - (face_detections.embedding <=> query_embedding) as similarity
  from face_detections
  where face_detections.evento_id = p_evento_id
    and 1 - (face_detections.embedding <=> query_embedding) > match_threshold
  order by face_detections.embedding <=> query_embedding
  limit match_count;
$function$;

create or replace function public.sugerir_candidatos(huella_dudosa extensions.vector, limite_resultados integer, id_evento text)
returns table(id_identidad uuid, nombre_jugador text, avatar text, porcentaje_similitud double precision)
language plpgsql security definer set search_path to 'public','extensions' as $function$
BEGIN
  RETURN QUERY
  SELECT id AS id_identidad, display_name AS nombre_jugador, avatar_url AS avatar,
         1.0 - (embedding_promedio <=> huella_dudosa) AS porcentaje_similitud
  FROM identities
  WHERE evento_id::text = id_evento AND embedding_promedio IS NOT NULL
  ORDER BY embedding_promedio <=> huella_dudosa ASC
  LIMIT limite_resultados;
END;
$function$;

create or replace function public.sugerir_candidatos(huella_dudosa extensions.vector, limite_resultados integer default 3)
returns table(id_identidad uuid, nombre_jugador text, avatar text, porcentaje_similitud double precision)
language plpgsql security definer set search_path to 'public','extensions' as $function$
BEGIN
    RETURN QUERY
    SELECT i.id, i.display_name, i.avatar_url, (1 - (i.embedding_promedio <=> huella_dudosa))
    FROM identities i
    WHERE i.embedding_promedio IS NOT NULL
    ORDER BY i.embedding_promedio <=> huella_dudosa ASC
    LIMIT limite_resultados;
END;
$function$;
